//! J288/S288 configuration protocol from the official Qt Motor Assistant SDK.
//! See docs/unitree-j288-id-protocol.md for provenance and SDK test vectors.
//! Only ID configuration and returning to APP are exposed to the serial worker.
use anyhow::{ensure, Result};

use crate::unitree_protocol::{control_packet, crc32, validate_id, ServoTarget};

pub fn enter_boot_packet(id: u8) -> Result<[u8; 20]> {
    let mut packet = control_packet(id, 0, false, ServoTarget::default())?;
    packet[2] = id | 0x70;
    let crc = crc32(&packet[..16]);
    packet[16..].copy_from_slice(&crc.to_le_bytes());
    Ok(packet)
}

#[derive(Clone, Debug)]
pub struct BootRequest {
    pub id: u8,
    pub length_code: u8,
    pub command: u8,
    pub address: u16,
    pub data: Vec<u8>,
}

impl BootRequest {
    pub fn challenge(id: u8) -> Self {
        Self {
            id,
            length_code: 8,
            command: 0,
            address: 0x20,
            data: vec![0xaa; 16],
        }
    }

    pub fn unlock(id: u8, challenge: &[u8]) -> Result<Self> {
        ensure!(
            challenge.len() == 16,
            "Invalid Flash unlock challenge length"
        );
        Ok(Self {
            id,
            length_code: 8,
            command: 1,
            address: 0x10,
            data: challenge.to_vec(),
        })
    }

    pub fn write_id(old_id: u8, new_id: u8) -> Result<Self> {
        validate_id(new_id)?;
        let mut data = vec![0; 8];
        data[0] = new_id;
        Ok(Self {
            id: old_id,
            length_code: 0,
            command: 1,
            address: 4,
            data,
        })
    }

    pub fn read_id(id: u8) -> Self {
        Self {
            id,
            length_code: 0,
            command: 0,
            address: 4,
            data: vec![0xaa; 8],
        }
    }

    pub fn save(id: u8, client_stamp: [u8; 8]) -> Self {
        Self {
            id,
            length_code: 0,
            command: 2,
            address: 0,
            data: client_stamp.to_vec(),
        }
    }

    pub fn restore_app(id: u8) -> Self {
        Self {
            id,
            length_code: 0,
            command: 5,
            address: 0,
            data: vec![0xaa; 8],
        }
    }

    pub fn packet(&self) -> Result<Vec<u8>> {
        validate_id(self.id)?;
        ensure!(
            (self.length_code == 0 && self.data.len() == 8)
                || (self.length_code == 8 && self.data.len() == 16),
            "Unsupported Boot payload length"
        );
        ensure!(
            self.address < 0x4000 && self.command < 16,
            "Invalid Boot command"
        );
        let mut packet = vec![0; self.data.len() + 12];
        packet[..8].copy_from_slice(&[
            0xfe,
            0xee,
            self.id | 0xf0,
            0,
            self.id | 0xf0,
            (self.length_code << 4) | self.command,
            self.address as u8,
            (self.address >> 8) as u8,
        ]);
        packet[8..8 + self.data.len()].copy_from_slice(&self.data);
        let end = packet.len() - 4;
        let crc = crc32(&packet[..end]);
        packet[end..].copy_from_slice(&crc.to_le_bytes());
        Ok(packet)
    }

    pub fn matches(&self, reply: &BootReply) -> bool {
        reply.id == self.id
            && reply.length_code == self.length_code
            && reply.command == self.command
            && reply.address == self.address
            && reply.sector == 0
    }
}

#[derive(Debug)]
pub struct BootReply {
    pub id: u8,
    pub acknowledged: bool,
    pub length_code: u8,
    pub command: u8,
    pub address: u16,
    pub sector: u8,
    pub data: Vec<u8>,
}

pub fn parse_boot_reply(packet: &[u8]) -> Result<BootReply> {
    ensure!(
        packet.len() >= 26 && packet[..2] == [0xfc, 0xee],
        "Invalid Boot reply header"
    );
    let code = packet[3] >> 4;
    ensure!(code == 0 || code == 8, "Unsupported Boot reply length code");
    let data_len = if code == 8 { 16 } else { 8 };
    ensure!(packet.len() == data_len + 18, "Invalid Boot reply length");
    let end = packet.len() - 4;
    ensure!(
        crc32(&packet[2..end]) == u32::from_le_bytes(packet[end..].try_into()?),
        "Boot reply CRC mismatch"
    );
    let id = packet[2] & 15;
    validate_id(id)?;
    Ok(BootReply {
        id,
        acknowledged: packet[2] & 0x80 != 0,
        length_code: code,
        command: packet[3] & 15,
        address: u16::from_le_bytes([packet[4], packet[5]]) & 0x3fff,
        sector: packet[5] >> 6,
        data: packet[6..6 + data_len].to_vec(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::unitree_protocol::hex_bytes;

    // Generated by emulating the unmodified official J288 packet constructor,
    // independently of this Rust implementation. No SDK binary is redistributed.
    #[test]
    fn official_sdk_packet_vectors() {
        let challenge: Vec<u8> = (0..16).collect();
        let vectors = [
            (BootRequest::challenge(0), "FE EE F0 00 F0 80 20 00 AA AA AA AA AA AA AA AA AA AA AA AA AA AA AA AA 1F 91 0B A9"),
            (BootRequest::unlock(0, &challenge).unwrap(), "FE EE F0 00 F0 81 10 00 00 01 02 03 04 05 06 07 08 09 0A 0B 0C 0D 0E 0F 70 A4 33 CC"),
            (BootRequest::write_id(0, 3).unwrap(), "FE EE F0 00 F0 01 04 00 03 00 00 00 00 00 00 00 C0 FB 66 FB"),
            (BootRequest::save(3, [0x19, 0xab, 0xcd, 0xef, 0x78, 0x56, 0x34, 0x12]), "FE EE F3 00 F3 02 00 00 19 AB CD EF 78 56 34 12 A6 70 FA E3"),
            (BootRequest::read_id(3), "FE EE F3 00 F3 00 04 00 AA AA AA AA AA AA AA AA 5D 61 4F E6"),
            (BootRequest::restore_app(3), "FE EE F3 00 F3 05 00 00 AA AA AA AA AA AA AA AA A9 42 EE 86"),
        ];
        for (request, expected) in vectors {
            assert_eq!(hex_bytes(&request.packet().unwrap()), expected);
        }
        assert!(BootRequest::write_id(0, 15).is_err());
        assert!(BootRequest::unlock(0, &[0; 8]).is_err());
        assert!(BootRequest::challenge(15).packet().is_err());
        let packet = enter_boot_packet(3).unwrap();
        assert_eq!(packet[2], 0x73);
        assert_eq!(
            crc32(&packet[..16]),
            u32::from_le_bytes(packet[16..].try_into().unwrap())
        );
    }

    #[test]
    fn reply_vectors_accepted_by_official_sdk_parser() {
        let vectors = [
            ("FC EE F0 80 20 00 00 01 02 03 04 05 06 07 08 09 0A 0B 0C 0D 0E 0F 00 00 00 00 00 00 00 00 99 75 1E E2", 8, 0, 32, 16),
            ("FC EE F0 81 10 00 00 01 02 03 04 05 06 07 08 09 0A 0B 0C 0D 0E 0F 00 00 00 00 00 00 00 00 16 15 B0 F1", 8, 1, 16, 16),
            ("FC EE F0 01 04 00 03 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 C5 05 CE 71", 0, 1, 4, 8),
            ("FC EE F0 02 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 31 A4 E4 E3", 0, 2, 0, 8),
        ];
        for (raw, code, command, address, length) in vectors {
            let mut packet: Vec<u8> = raw
                .split_whitespace()
                .map(|s| u8::from_str_radix(s, 16).unwrap())
                .collect();
            let reply = parse_boot_reply(&packet).unwrap();
            assert!(reply.acknowledged);
            assert_eq!(
                (
                    reply.id,
                    reply.length_code,
                    reply.command,
                    reply.address,
                    reply.sector
                ),
                (0, code, command, address, 0)
            );
            assert_eq!(reply.data.len(), length);
            packet[6] ^= 1;
            assert!(parse_boot_reply(&packet).is_err());
            assert!(parse_boot_reply(&packet[..packet.len() - 1]).is_err());
        }
    }
}
